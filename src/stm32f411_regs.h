#ifndef STM32F411_REGS_H
#define STM32F411_REGS_H

/* RCC */
#define RCC_AHB1ENR_ADDR 0x40023830u
#define RCC_APB1ENR_ADDR 0x40023840u

#define RCC_AHB1ENR_GPIOAEN_MASK (1u << 0)
#define RCC_APB1ENR_USART2EN_MASK (1u << 17)

/* GPIOA */
#define GPIOA_MODER_ADDR 0x40020000u
#define GPIOA_BSRR_ADDR 0x40020018u
#define GPIOA_AFRL_ADDR 0x40020020u

#define GPIOA_MODER_PA2_MASK (3u << 4)
#define GPIOA_MODER_PA3_MASK (3u << 6)
#define GPIOA_MODER_PA5_MASK (3u << 10)

#define GPIOA_MODER_PA2_AF (2u << 4)
#define GPIOA_MODER_PA3_AF (2u << 6)
#define GPIOA_MODER_PA5_OUTPUT (1u << 10)

#define GPIOA_AFRL_PA2_MASK (15u << 8)
#define GPIOA_AFRL_PA3_MASK (15u << 12)
#define GPIOA_AFRL_PA2_AF7 (7u << 8)
#define GPIOA_AFRL_PA3_AF7 (7u << 12)

#define GPIOA_BSRR_BS5 (1u << 5)
#define GPIOA_BSRR_BR5 (1u << 21)

/* USART2 */
#define USART2_SR_ADDR 0x40004400u
#define USART2_DR_ADDR 0x40004404u
#define USART2_BRR_ADDR 0x40004408u
#define USART2_CR1_ADDR 0x4000440Cu

#define USART_SR_TXE (1u << 7)
#define USART_SR_TC (1u << 6)
#define USART_CR1_UE (1u << 13)
#define USART_CR1_TE (1u << 3)

/* SysTick */
#define STK_CTRL_ADDR 0xE000E010u
#define STK_LOAD_ADDR 0xE000E014u
#define STK_VAL_ADDR 0xE000E018u

#define STK_CTRL_ENABLE_MASK (1u << 0)
#define STK_CTRL_TICKINT_MASK (1u << 1)
#define STK_CTRL_CLKSOURCE_MASK (1u << 2)

#endif
