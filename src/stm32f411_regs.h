#define RCC_AHB1ENR_GPIOAEN_MASK (1u << 0)
#define RCC_APB1ENR_USART2EN_MASK (1u << 17)

#define GPIOA_MODER_MODER_5_MASK (3u << 10)
#define GPIOA_MODER_MODER_5_OUTPUT (1u << 10)

